MESSAGE = """    message: >-
      Content the application fetched or looked up (a retrieved document, a web page or HTTP
      response body, a search result, an MCP server's tool result, or the text of a stored
      ticket, message, or comment), or a model's answer about it, is written to the agent's
      long-term memory without review. Memory is read back into the prompt in later sessions,
      often for other users or other agents, so instructions planted in that content keep
      steering the agent after the page or ticket is gone (memory poisoning): they can change
      what it tells people, which tools it calls, and where it sends data. Screen what you store
      for instructions and keep it to facts you extracted and checked, record where each memory
      came from, and keep memory from untrusted sources scoped to the user or tenant it came
      from, apart from memory the agent treats as its own.
"""

# Names a check or clean-up step goes by: sanitize_memory(text), screen_for_injection(page),
# guard.validate(note), moderate(text). Counts as review, here and as `if not is_safe(x): ...`.
# Not schema parsing (pydantic model_validate, TypeAdapter.validate_json), which checks shape only.
REVIEW_NAME = (r"(?i)^(?![\w$.]*(?:model_validate|validate_(?:json|python|strings)|parse_obj))"
               r"(?:[\w$.]*[._])?_?(?:[\w$]*_)?(?:sanitiz|validat|moderat|review|screen|vet_|scan_?for"
               r"|detect_?injection|check_?injection|strip_?instructions|is_?safe|looks_?safe|is_?clean)[\w$]*$")


