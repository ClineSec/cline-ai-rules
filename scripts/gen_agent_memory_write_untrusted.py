#!/usr/bin/env python3
"""Generate agent-memory-write-untrusted (Python) and agent-memory-write-untrusted-ts.

Both rules take their sources from gen_fetched_content_in_system_prompt.py: content the
application fetched or looked up (retrieved documents, web pages and HTTP bodies, search
results, MCP tool results, and the free text of stored records), plus that rule's slice sources,
propagators, and value sanitizers. build.py lists the shared slices in SHARED_BLOCKS. What
differs is the sink: a write to long-term agent memory that a later session reads back into the
prompt (mem0, a LangGraph store, Letta memory blocks and archival passages, a Zep graph or
thread), instead of the system prompt.

Model output on its own is not a source. Storing the conversation, the model's reply included,
is the documented core use of mem0 and Zep, so that source would flag every integration. A
model's answer about fetched content still carries the content's taint through the model call
(summary = llm.invoke(f"Summarize {page}")), so summarizing a page and storing the summary is
reported.

Edit this script, not the rule files. scripts/build.py regenerates them, and
scripts/build.py --check fails when a rule file differs from what this script produces.

Usage:
    python3 scripts/gen_agent_memory_write_untrusted.py    # rewrite the two rule files
"""

