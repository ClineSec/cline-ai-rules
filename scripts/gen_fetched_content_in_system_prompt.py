# OpenGrep 1.30.2 drops taint at a Python slice (text[:8000], docs[:3], resp.text[:4000]): the
# slice comes out clean, and a sink on the sliced name doesn't fire either. Fetched text is
# usually cut to fit the context window, so a slice is a source itself when what it slices
# visibly came from a source: inline, one assignment back, or through a loop variable.


def indent(text: str, n: int) -> str:
    return "".join(" " * n + line + "\n" if line else "\n" for line in text.splitlines())


def shape(pattern: str, *conds: tuple[str, str]) -> str:
    """One pattern-either item: a pattern plus metavariable-regex conditions."""
    if not conds:
        return f"- pattern: {pattern}"
    out = f"- patterns:\n    - pattern: {pattern}\n"
    for var, regex in conds:
        out += mvr(var, regex, 4, literal=True)
    return out.rstrip("\n")


def shapes_of(metavariable: str, items: list[str], n: int) -> str:
    """A metavariable-pattern that matches any of `items` anywhere inside `metavariable`, after
    the guard against OpenGrep's crash on a parenthesized receiver (gen_mcp_unpinned.py)."""
    out = f"- metavariable-pattern:\n    metavariable: {metavariable}\n    pattern-either:\n"
    out += "".join(indent(item, 6) for item in items)
    return paren_guard(metavariable, n) + indent(out.rstrip("\n"), n)


