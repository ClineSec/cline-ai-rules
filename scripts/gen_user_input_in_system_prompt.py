# How many other messages may follow the system message in a template the rule recognizes.
TEMPLATE_MAX_OTHERS = 3

TEMPLATE_NOTE = """      # A LangChain{js} prompt template whose system message has a {{placeholder}}, filled from
      # the request when the template, or a chain built on it, is invoked or formatted:
      # {examples}. The system template is inline or a module constant. The key must appear in
      # the system template and in none of the other messages, so a key that only names a word
      # in the system text ("answer questions") and fills {{question}} in the human message
      # doesn't count; OpenGrep can't compare a key with each {{placeholder}} exactly. Templates
      # whose system message isn't first, or with more than {n} other messages, are not
      # recognized.
"""


def template_sinks(regions: list[str], invocations: list[str], inv_regex: str | None) -> str:
    """One sink per number of messages after the system message ($M1 ... $Mn), so the key can
    be checked against each of them. `regions` hold {others} where the `, $M1, ...` list goes.
    With inv_regex None, the invocations don't bind $INV (a chain piped into the template)."""
    out = ""
    for n in range(TEMPLATE_MAX_OTHERS + 1):
        others = "".join(f", $M{i}" for i in range(1, n + 1))
        out += "      - patterns:\n          - pattern-either:\n"
        for region in regions:
            out += "              - pattern-inside: |\n"
            out += "".join(f"                  {line}\n" for line in region.format(others=others).splitlines())
        out += "          - pattern-either:\n"
        for inv in invocations:
            out += "".join(f"              {line}\n" for line in inv.splitlines())
        if inv_regex:
            out += mvr("$INV", inv_regex, 10)
        cond = "str($K) in str($T)" + "".join(f" and not (str($K) in str($M{i}))" for i in range(1, n + 1))
        out += f"          - metavariable-comparison:\n              comparison: {cond}\n"
        out += "          - focus-metavariable: $X\n"
    return out


