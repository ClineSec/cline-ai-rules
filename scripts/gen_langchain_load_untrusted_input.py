# ---- Python --------------------------------------------------------------------------------

# The modules that export load / loads: langchain_core.load re-exports langchain_core.load.load,
# and langchain (0.x) and langchain-classic re-export both.
PY_LOAD_MODULES = ("langchain_core.load", "langchain_core.load.load", "langchain.load",
                   "langchain.load.load", "langchain_classic.load", "langchain_classic.load.load")
PY_REVIVERS = ("langchain_core.load.load.Reviver", "langchain.load.load.Reviver",
               "langchain_classic.load.load.Reviver")
# An allowed_objects list or tuple of message and document classes only.
PY_NARROW_LIST = (r"^[\[(]\s*(?:[\w.]*(?:Message|MessageChunk|Document)\s*,\s*)*"
                  r"[\w.]*(?:Message|MessageChunk|Document)\s*,?\s*[\])]$")
# Any other value that isn't a list literal or the string "core" / "all": "messages", or a
# name the rule can't see into (a constant list of classes the application chose).
PY_OTHER_VALUE = r"""^(?![\[(]|[rRuU]?["'](?:core|all)["']$)"""
PY_ENV_MAP = (r"(?s)^(?:(?:os\.)?environ(?:\.copy\(\))?|dict\(\s*(?:os\.)?environ\s*[,)].*"
              r"|\{\s*\*\*(?:os\.)?environ\s*[,}].*)$")


def py_sinks() -> str:
    calls = []
    for mod in PY_LOAD_MODULES:
        for fn in ("load", "loads"):
            kw = "obj" if fn == "load" else "text"
            calls.append(f"{mod}.{fn}($X, ...)")
            calls.append(f"{mod}.{fn}(..., {kw}=$X, ...)")
    for rev in PY_REVIVERS:
        calls.append(f"json.loads($X, ..., object_hook={rev}(...), ...)")
    body = "".join(f"              - pattern: {c}\n" for c in calls)
    return f"""    pattern-sinks:
      # The payload: load(obj) / loads(text), first argument or keyword, and the text json.loads
      # parses with a LangChain Reviver as its object_hook.
      - patterns:
          - pattern-either:
{body}          # Narrow allowlists stand down: allowed_objects="messages", a list of message and
          # document classes, or a value the rule can't see into. (On 0.3.x, secret references
          # are still read from the environment unless secrets_from_env=False; the message
          # says so, but the rule can't tell the installed version.)
          - pattern-not-inside:
              patterns:
                - pattern: $G(..., allowed_objects=$AO, ...)
{mvr('$AO', PY_OTHER_VALUE, 16, literal=True)}          - pattern-not-inside:
              patterns:
                - pattern: $G(..., allowed_objects=$AO, ...)
{mvr('$AO', PY_NARROW_LIST, 16, literal=True)}          - pattern-not-inside: $G(..., object_hook=$R("messages", ...), ...)
          - pattern-not-inside: $G(..., object_hook=$R([...], ...), ...)
          - pattern-not-inside: $G(..., object_hook=$R(..., allowed_objects=$AO, ...), ...)
          # Calls langchain-load-unsafe-objects reports.
          - pattern-not-inside: $G(..., allowed_objects="all", ...)
          - pattern-not-inside: $G(..., secrets_from_env=True, ...)
          - pattern-not-inside: $G(..., init_validator=None, ...)
          - pattern-not-inside: $G(..., object_hook=$R("all", ...), ...)
          - pattern-not-inside: $G(..., object_hook=$R(..., secrets_from_env=True, ...), ...)
          - pattern-not-inside:
              patterns:
                - pattern: $G(..., secrets_map=$SM, ...)
{mvr('$SM', PY_ENV_MAP, 16, literal=True)}          - focus-metavariable: $X
"""


PY_CHECKED = ("2026-10-25: langchain-core 1.7.0, 1.3.3, 1.2.5, 0.3.86, 0.3.81, 0.3.80\n"
              "    # (langchain_core/load/load.py), langchain-classic 1.0.8 (load/)")

PY_REFS = """        - https://github.com/langchain-ai/langchain/blob/langchain-core%3D%3D1.7.0/libs/core/langchain_core/load/load.py
"""


def py_rule() -> str:
    s = "rules:\n  - id: langchain-load-untrusted-input\n"
    s += SYNC_NOTE.format(suffix="", checked=PY_CHECKED)
    s += "    languages: [python]\n    severity: WARNING\n"
    s += PY_MESSAGE
    s += OPTIONS + PY_SOURCES + PY_SANITIZERS + py_sinks()
    s += metadata("[flask, django, fastapi, starlette, langchain]", PY_REFS)
    return s


# ---- TypeScript / JavaScript ---------------------------------------------------------------

TS_LOAD_MODULE = r"=~/^(?:@langchain\/core\/load|langchain\/load)$/"


def ts_sinks() -> str:
    mod = f'"{TS_LOAD_MODULE}"'
    return f"""    pattern-sinks:
      # The text handed to @langchain/core/load or langchain/load load(text, ...).
      - patterns:
          - pattern-either:
              - patterns:
                  - pattern-either:
                      - pattern-inside: |
                          import {{ load }} from {mod};
                          ...
                      - pattern-inside: |
                          const {{ load }} = require({mod});
                          ...
                  - pattern-either:
                      - pattern: load($X, ...)
                      # OpenGrep 1.30.2 parses `await load<T>(x)` as a call whose callee is
                      # `await load`, so a generic call under await needs its own shape.
                      - patterns:
                          - pattern: $AW($X, ...)
                          - metavariable-pattern:
                              metavariable: $AW
                              language: generic
                              pattern: await load
              - patterns:
                  - pattern-either:
                      - pattern-inside: |
                          import {{ load as $L }} from {mod};
                          ...
                      - pattern-inside: |
                          const {{ load: $L }} = require({mod});
                          ...
                  - pattern-either:
                      - pattern: $L($X, ...)
                      # OpenGrep 1.30.2 parses `await load<T>(x)` as a call whose callee is
                      # `await load`, so a generic call under await needs its own shape.
                      - patterns:
                          - pattern: $AW($X, ...)
                          - metavariable-pattern:
                              metavariable: $AW
                              language: generic
                              pattern: await $L
              - patterns:
                  - pattern-either:
                      - pattern-inside: |
                          import * as $NS from {mod};
                          ...
                      - pattern-inside: |
                          const $NS = require({mod});
                          ...
                  - pattern-either:
                      - pattern: $NS.load($X, ...)
                      # OpenGrep 1.30.2 parses `await load<T>(x)` as a call whose callee is
                      # `await load`, so a generic call under await needs its own shape.
                      - patterns:
                          - pattern: $AW($X, ...)
                          - metavariable-pattern:
                              metavariable: $AW
                              language: generic
                              pattern: await $NS.load
          # Calls langchain-load-unsafe-objects-ts reports: secretsFromEnv turned on (inline,
          # in a const options object, or langchain/load's fifth argument) or the whole
          # environment as the secrets map.
          - pattern-not-inside: '$G($Y, {{..., secretsFromEnv: true, ...}}, ...)'
          - pattern-not-inside: '$G($Y, {{..., secretsMap: process.env, ...}}, ...)'
          - pattern-not-inside: $G($Y, $SM, $OM, $AM, true)
          - pattern-not-inside: $G($Y, process.env, ...)
          - pattern-not-inside: |
              const $OPTS = {{..., secretsFromEnv: true, ...}};
              ...
              $G($Y, $OPTS);
          - focus-metavariable: $X
"""


TS_CHECKED = ("2026-10-25: @langchain/core 1.3.0, 1.1.8, 1.1.7, 0.3.80, 0.3.79\n"
              "    # (dist/load/index.js), langchain 1.5.19 (dist/load/index.js)")

TS_REFS = """        - https://www.npmjs.com/package/@langchain/core/v/1.3.0
"""


def ts_rule() -> str:
    s = "rules:\n  - id: langchain-load-untrusted-input-ts\n"
    s += SYNC_NOTE.format(suffix="-ts", checked=TS_CHECKED)
    s += "    languages: [typescript, javascript]\n    severity: WARNING\n"
    s += TS_MESSAGE
    s += OPTIONS + TS_SOURCES + TS_SANITIZERS + ts_sinks()
    s += metadata("[express, nextjs, hono, node, langchain]", TS_REFS)
    return s


def render() -> dict[Path, str]:
    """The two rule files and the content this script generates for each."""
    return {PY_RULE: py_rule(), TS_RULE: ts_rule()}


def main() -> int:
    for path, content in render().items():
        path.parent.mkdir(parents=True, exist_ok=True)
        if not path.exists() or path.read_text() != content:
            path.write_text(content)
            print(f"wrote {path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
