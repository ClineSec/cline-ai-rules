#!/usr/bin/env python3
"""Generate langchain-load-untrusted-input (Python) and langchain-load-untrusted-input-ts.

Both rules read request data with the sources and sanitizers of user-input-in-system-prompt
(imported from gen_user_input_in_system_prompt.py; build.py SHARED_BLOCKS checks the copy). The
sink is the payload of LangChain's object reviver: langchain_core.load load() / loads() (and the
langchain / langchain-classic re-exports, and json.loads with a LangChain Reviver hook) in
Python, and @langchain/core/load or langchain/load load() in TypeScript.

Calls that langchain-load-unsafe-objects(-ts) reports (allowed_objects="all",
secrets_from_env=True, init_validator=None, the whole environment as the secrets map) are left
to that rule, so each call is reported once.

Edit this script, not the rule files. scripts/build.py regenerates them, and
scripts/build.py --check fails when a rule file differs from what this script produces.

Usage:
    python3 scripts/gen_langchain_load_untrusted_input.py    # rewrite the two rule files
"""

