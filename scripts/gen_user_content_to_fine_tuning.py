def ts_rule() -> str:
    s = "rules:\n  - id: user-content-to-fine-tuning-ts\n"
    s += SYNC_NOTE.format(suffix="-ts", checked=TS_CHECKED)
    s += "    languages: [typescript, javascript]\n    severity: WARNING\n" + TS_PATHS
    s += MESSAGE.format(sink="a file uploaded with `purpose: \"fine-tune\"`, or a file named like training\n"
                             "      data")
