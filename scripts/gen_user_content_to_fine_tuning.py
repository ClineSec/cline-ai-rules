def py_admin_exclusions() -> str:
    """Handlers only an administrator can call: an admin decorator or route, an admin
    dependency, or an admin check at the top of the body."""
    # `@$D` matches only bare-name decorators, and `(..., $A, ...)` only positional arguments,
    # so calls (`@router.post("/admin/x")`, `dependencies=[Depends(require_admin)]`,
    # `@user_passes_test(lambda u: u.is_superuser)`) are matched by name and by argument.
    out = "          # Handlers only an administrator can call: that is how vetted datasets get in.\n"
    for deco, var in (("@$ADMDEC", "$ADMDEC"), ("@$ADMDEC(...)", "$ADMDEC"),
                      ("@$ADMDEC(..., $ADMARG, ...)", "$ADMARG"),
                      ("@$ADMDEC(..., $ADMKW=$ADMARG, ...)", "$ADMARG")):
        out += """          - pattern-not-inside:
              patterns:
                - pattern-either:
                    - pattern-inside: |
                        """ + deco + """
                        def $ADMFN(...): ...
                    - pattern-inside: |
                        """ + deco + """
                        async def $ADMFN(...): ...
""" + mvr(var, PY_ADMIN_DECORATOR, 16, literal=True)
    return out + """          - pattern-not-inside:
              patterns:
                - pattern-either:
                    - pattern-inside: |
                        def $ADMFN(..., $ADMP = $ADMDEP, ...): ...
                    - pattern-inside: |
                        async def $ADMFN(..., $ADMP = $ADMDEP, ...): ...
                    - pattern-inside: |
                        def $ADMFN(..., $ADMP: $ADMDEP, ...): ...
                    - pattern-inside: |
                        async def $ADMFN(..., $ADMP: $ADMDEP, ...): ...
                    - pattern-inside: |
                        def $ADMFN(..., $ADMP: $ADMT = $ADMDEP, ...): ...
                    - pattern-inside: |
                        async def $ADMFN(..., $ADMP: $ADMT = $ADMDEP, ...): ...
""" + mvr("$ADMDEP", PY_ADMIN_DEP, 16, literal=True) + """          - pattern-not-inside:
              patterns:
                - pattern-inside: |
                    if not $ADMU.$ADMA:
                      ...
                    ...
""" + mvr("$ADMA", PY_ADMIN_ATTR, 16) + """          - pattern-not-inside:
              patterns:
                - pattern-either:
                    - pattern-inside: |
                        $ADMCHK(...)
                        ...
                    - pattern-inside: |
                        await $ADMCHK(...)
                        ...
""" + mvr("$ADMCHK", PY_ADMIN_CALL, 16)


