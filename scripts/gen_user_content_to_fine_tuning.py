def path_check(var: str, n: int) -> str:
    """The text bound to `var` names training data: a string in it matches (module constants
    included, through constant propagation), or its own text does (TRAINING_FILE, sft_dir).
    A bare `pattern: $V` here would crash OpenGrep on a parenthesized expression
    (`(DATA_DIR / "x").write_text(...)`), so the text check is a pattern-regex."""
    pad = " " * n
    return (f"{pad}- metavariable-pattern:\n{pad}    metavariable: {var}\n{pad}    pattern-either:\n"
            f"{pad}      - pattern: '\"=~/{TRAIN_WORD}/\"'\n"
            f"{pad}      - pattern-regex: {TRAIN_WORD}\n")


def ind(text: str, n: int) -> str:
    pad = " " * n
    return "".join(pad + line if line.strip() else line for line in text.splitlines(keepends=True))


