def header(key):
    rid = RULE_ID + "-" + key
    c = CLIENTS[key]
    s = f"rules:\n  - id: {rid}\n" + ind(SYNC_NOTE, 4)
    if key == "toml":
        s += "    # Regex, not a parser: OpenGrep has no TOML support.\n"
    lang = {"yaml": "yaml", "toml": "regex", "opencode": "regex"}.get(key, "json")
    s += f"    languages: [{lang}]\n    severity: WARNING\n"
    text = LEAD.format(who=c["who"]) + c["how"] + TAIL
    s += "    message: >-\n" + wrap(text, 6)
    s += ind(c["note"], 4)
    return s


def wrap(text, n, width=96):
    out, line = [], ""
    for word in text.split():
        if line and len(line) + 1 + len(word) + n > width:
            out.append(line)
            line = word
        else:
            line = f"{line} {word}" if line else word
    out.append(line)
    return "".join(" " * n + ln + "\n" for ln in out)


def paths(key):
    c = CLIENTS[key]
