#!/usr/bin/env python3
"""Regenerate taxonomy/aisvs.yaml and taxonomy/atlas.yaml from pinned upstream releases.

The sources are read from local paths, so fetch them yourself at the pinned versions:

    # OWASP AISVS: a checkout or tarball of the release tag (CC BY-SA 4.0)
    curl -sSfL https://codeload.github.com/OWASP/AISVS/tar.gz/refs/tags/v1.01 | tar -xz
    # MITRE ATLAS: the release file from atlas-data (Apache 2.0)
    curl -sSfLO https://raw.githubusercontent.com/mitre-atlas/atlas-data/v2026.09/dist/v6/ATLAS-2026.09.yaml

Usage:
    python3 scripts/update_taxonomy.py --aisvs AISVS-1.01/ --aisvs-version 1.01 \
        --aisvs-commit <sha> --atlas ATLAS-2026.09.yaml --atlas-commit <sha>

Only IDs and short titles are kept: AISVS section titles (requirements have none) and ATLAS
technique names, with sub-techniques written "Parent: Sub" as ATLAS displays them.
"""

from __future__ import annotations

import argparse
import hashlib
import re
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
SECTION_RE = re.compile(r"^## (C\d+\.\d+|AC\.\d+) (.+?)\s*$")
REQUIREMENT_RE = re.compile(r"^\|\s*\*\*(AC\.\d+\.\d+|\d+\.\d+\.\d+)\*\*\s*\|")


def quote(value: str) -> str:
    return yaml.safe_dump(value, width=1000).removesuffix("\n...\n").strip()


def aisvs_sections(chapters: Path) -> dict[str, dict]:
    sections: dict[str, dict] = {}
    for md in sorted(chapters.glob("0x*.md")):
        current = None
        for line in md.read_text().splitlines():
            if m := SECTION_RE.match(line):
                current = m.group(1)
                sections[current] = {"title": m.group(2), "requirements": []}
            elif (m := REQUIREMENT_RE.match(line)) and current:
                req = m.group(1) if m.group(1).startswith("AC.") else f"C{m.group(1)}"
                if not req.startswith(current + "."):
                    raise SystemExit(f"{md.name}: {req} found under section {current}")
                sections[current]["requirements"].append(req)
    return {k: v for k, v in sections.items() if v["requirements"]}


def write_aisvs(src: Path, version: str, commit: str) -> int:
    sections = aisvs_sections(src / version / "en")
    total = sum(len(s["requirements"]) for s in sections.values())
    lines = [
        "# OWASP AISVS requirement IDs that rule metadata may use (field: owasp-aisvs).",
        "# Generated by scripts/update_taxonomy.py; do not edit by hand.",
        "#",
        "# Tags use AISVS's own citation form, v<version>-C<chapter>.<section>.<requirement>",
        "# (AC.<section>.<requirement> for Appendix C), followed by the section title because",
        "# requirements have no titles: \"v1.01-C10.3.3 - Secure Transport\".",
        "#",
        f"# Source: OWASP/AISVS {version}/en/ at commit {commit}.",
        "# IDs and section titles extracted and reformatted from OWASP AISVS, (c) The AISVS",
        "# Project, licensed CC BY-SA 4.0: https://creativecommons.org/licenses/by-sa/4.0/",
        f"# {len(sections)} sections, {total} requirements.",
        "",
        f"version: {quote(version)}",
        f"source: https://github.com/OWASP/AISVS/tree/v{version}/{version}/en",
        "sections:",
    ]
    for sid, s in sections.items():
        reqs = ", ".join(s["requirements"])
        lines.append(f"  {quote(sid)}:")
        lines.append(f"    title: {quote(s['title'])}")
        lines.append(f"    requirements: [{reqs}]")
    (ROOT / "taxonomy" / "aisvs.yaml").write_text("\n".join(lines) + "\n")
    return total


def write_atlas(src: Path, commit: str) -> int:
    raw = src.read_bytes()
    data = yaml.safe_load(raw)
    version = data["collection"]["version"]
    techniques = data["techniques"]
    names = {}
    for tid in sorted(techniques):
        parent, _, sub = tid.rpartition(".") if tid.count(".") == 2 else (tid, "", "")
        name = techniques[tid]["name"]
        names[tid] = f"{techniques[parent]['name']}: {name}" if sub else name
    lines = [
        "# MITRE ATLAS technique IDs that rule metadata may use (field: mitre-atlas).",
        "# Generated by scripts/update_taxonomy.py; do not edit by hand.",
        "#",
        "# ATLAS retires and renames techniques between releases without stubs, so tags are",
        "# validated against this pinned release. Sub-techniques read \"Parent: Sub\".",
        "#",
        f"# Source: mitre-atlas/atlas-data dist/v6/{src.name} at commit {commit},",
        f"# sha256 {hashlib.sha256(raw).hexdigest()}. {len(names)} techniques and sub-techniques.",
        "# IDs and names extracted and reformatted from MITRE ATLAS, Copyright 2021-2026 MITRE,",
        "# licensed Apache 2.0: https://www.apache.org/licenses/LICENSE-2.0",
        "",
        f"version: {quote(version)}",
        f"source: https://github.com/mitre-atlas/atlas-data/blob/v{version}/dist/v6/{src.name}",
        "techniques:",
    ]
    lines += [f"  {quote(tid)}: {quote(name)}" for tid, name in names.items()]
    (ROOT / "taxonomy" / "atlas.yaml").write_text("\n".join(lines) + "\n")
    return len(names)


def main() -> int:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--aisvs", type=Path, required=True, help="AISVS repository root")
    p.add_argument("--aisvs-version", required=True, help="release folder, e.g. 1.01")
    p.add_argument("--aisvs-commit", required=True)
    p.add_argument("--atlas", type=Path, required=True, help="ATLAS-<version>.yaml")
    p.add_argument("--atlas-commit", required=True)
    args = p.parse_args()
    reqs = write_aisvs(args.aisvs, args.aisvs_version, args.aisvs_commit)
    techs = write_atlas(args.atlas, args.atlas_commit)
    print(f"wrote taxonomy/aisvs.yaml ({reqs} requirements) and taxonomy/atlas.yaml ({techs} techniques)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
