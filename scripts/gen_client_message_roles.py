def alt(*regexes: str) -> str:
    """One anchored regex matching any of several anchored ones."""
    return "^(?:" + "|".join(r.removeprefix("^").removesuffix("$") for r in regexes) + ")$"


def strip_comments(block: str, strip: bool) -> str:
    """Drop YAML comment lines, so a scaffold repeated in each sink is explained once."""
    if not strip:
        return block
    return "".join(line for line in block.splitlines(keepends=True) if not line.lstrip().startswith("#"))


def runs_tools(regex: str, n: int = 10, note: bool = False) -> str:
    """A raw provider sink's gate: no finding in a file that shows no sign of running tool calls."""
    pad = " " * n
    s = f"{pad}# Only where this file runs the tool calls itself (the generator's *_RUNS_TOOLS).\n" if note else ""
    return s + f"{pad}- pattern-not-regex: |-\n" + "".join(f"{pad}    {line}\n" for line in regex.splitlines())


