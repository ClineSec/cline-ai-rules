def ts_call_sink(note: str, call: str, key: str, call_regex: str | None, tools_keys: str,
                 requires: str, extra: str = "", first: bool = False, raw: bool = False) -> str:
    """One sink: the `key` value of an options-object call that also has tools. A raw call only
    returns the model's tool calls, so it reports only where the file runs them."""
    s = f"      # {note}\n" if note else ""
    s += f"      - requires: {requires}\n        patterns:\n"
    s += f"          - pattern-inside: '{call}({{..., {key}: $M, ...}}, ...)'\n"
    if call_regex:
        s += mvr("$CALL", call_regex, 10, literal=True)
    s += "          - pattern-either:\n"
    for tk in tools_keys.split("|"):
        s += f"              - pattern-inside: '{call}({{..., {tk}: $T, ...}}, ...)'\n"
    s += strip_comments(TS_TOOLS_IN_CONFIG, not first).format(call=call, keys=tools_keys)
    s += strip_comments(TS_NO_TOOLS, not first).format(call=call)
    s += extra
    if raw:
        s += runs_tools(TS_RUNS_TOOLS)
    s += "          - focus-metavariable: $M\n"
    return s


