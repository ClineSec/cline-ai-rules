def ts_tool_values(origin: str, n: int) -> str:
    """pattern-either items: the call's tool list is `origin`, a method call on it
    ((tools ?? []).map(addAuth), tools.filter(...)), or a const holding either. A helper call
    (toolsetFor(enabledTools)) or a server list filtered by client names doesn't count."""
    pad = " " * n
    s = ""
    for v in (origin, f"<... {origin} ...>.$TM(...)"):
        s += f"{pad}- pattern-inside: '{{..., tools: {v}, ...}}'\n"
    s += f"{pad}- patterns:\n{pad}    - pattern-inside: '{{..., tools: $T, ...}}'\n{pad}    - pattern-either:\n"
    for v in (origin, f"<... {origin} ...>.$TM(...)"):
        s += f"{pad}        - pattern-inside: |\n{pad}            const $T = {v};\n{pad}            ...\n"
    return s


