def call_sinks(sinks: list[tuple[str, dict[str, str]]]) -> str:
    """One sink for every call shape: each branch binds the value $X, and the finding lands on
    it. A `pattern-inside` region plus `pattern: $X` would first match every expression in the
    file; matching the call and focusing is several times cheaper."""
    out = "      - patterns:\n          - pattern-either:\n"
    for region, conds in sinks:
        quoted = region if "\n" in region else f"'{region}'"
        if conds:
            out += f"              - patterns:\n                  - pattern: {quoted}\n"
            out += "".join(mvr(var, regex, 18, literal=True) for var, regex in conds.items())
        else:
            out += f"              - pattern: {quoted}\n"
    return out + "          - focus-metavariable: $X\n"


