def _branches(templates: list[str], n: int) -> str:
    out = ""
    for key in PY_DICT_KEY_NAMES:
        for t in templates:
            t = t.replace("KEY", key)
            if "\n" in t:
                out += f"{' ' * n}- pattern: |\n" + "".join(f"{' ' * (n + 4)}{line}\n" for line in t.splitlines())
            else:
                out += f"{' ' * n}- pattern: '{t}'\n"
    return out


