def fix(prompt: str) -> None:
    # A name second in the argv, after a wrapper.
    # ruleid: ai-cli-bypass-flag-invocation-py
    subprocess.run(["sudo", CLAUDE_BIN, "-p", prompt, "--dangerously-skip-permissions"])
    # A string anywhere in the argv.
    # ruleid: ai-cli-bypass-flag-invocation-py
    subprocess.run(["nice", "-n", "10", "codex", "exec", "--yolo", prompt])
    # A constant holding the program, third in the argv.
    # ruleid: ai-cli-bypass-flag-invocation-py
    subprocess.run(["timeout", "600", AGENT_PROGRAM, "-p", prompt, "--dangerously-skip-permissions"])
    # ruleid: ai-cli-bypass-flag-invocation-py
    subprocess.run(("timeout", "600", "gemini", "-p", prompt, "--approval-mode", "yolo"))
    # A name anywhere after a known wrapper or runner.
    # ruleid: ai-cli-bypass-flag-invocation-py
    subprocess.run(["timeout", "600", CLAUDE_BIN, "-p", prompt, "--dangerously-skip-permissions"])
    # ruleid: ai-cli-bypass-flag-invocation-py
    subprocess.run(["sudo", "-u", "ci", CLAUDE_BIN, "-p", prompt, "--dangerously-skip-permissions"])
    # ruleid: ai-cli-bypass-flag-invocation-py
    subprocess.run(["nice", "-n", "10", CODEX, "exec", "--yolo", prompt])
    # ruleid: ai-cli-bypass-flag-invocation-py
    subprocess.run(["env", "NO_COLOR=1", "CI=1", CLAUDE_BIN, "-p", prompt, "--dangerously-skip-permissions"])
    # ruleid: ai-cli-bypass-flag-invocation-py
