REPO = os.environ.get("BUILDBOX_REPO", "/srv/buildbox/repo")


def propose_fixes(batch: list[str]) -> None:
    prompt = "Propose fixes for these flaky tests: " + ", ".join(batch)
    subprocess.run(
        [
            "nice",
            "-n",
            "10",
            "claude",
            "-p",
            prompt,
            "--output-format",
            "json",
            "--dangerously-skip-permissions",
        ],
        check=True,
        cwd=REPO,
    )


def summarize(batch: list[str]) -> None:
    prompt = "Group these flaky tests by likely cause: " + ", ".join(batch)
    subprocess.run(["claude", "-p", prompt, "--permission-mode", "plan"], check=True, cwd=REPO)


if __name__ == "__main__":
    tests = QUARANTINED[:20]
    if sys.argv[1:] == ["--summary"]:
        summarize(tests)
    else:
        propose_fixes(tests)
