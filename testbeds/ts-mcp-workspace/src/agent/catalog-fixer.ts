const CLAUDE = process.env.CLAUDE_BIN ?? "claude";

/** Runs the catalog fixer under a time limit, so a stuck session can't hold the runner. */
export function runCatalogFixer(prompt: string) {
  return spawn("timeout", ["900", CLAUDE, "-p", prompt, "--output-format", "json", "--dangerously-skip-permissions"], {
    stdio: "inherit",
  });
}

/** Read-only: which catalogs fail to parse. */
export function listBrokenCatalogs() {
  const prompt = `List which of these ${LOCALE_CATALOGS.length} catalogs fail to parse.`;
  return spawn(CLAUDE, ["-p", prompt, "--permission-mode", "plan"], { stdio: "inherit" });
}
